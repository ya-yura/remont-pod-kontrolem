export function getTodayIsoDate(): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

export function splitArticlesByReleaseDate(referenceIsoDate = getTodayIsoDate()): {
  published: DiyArticleItem[];
  upcoming: DiyArticleItem[];
} {
  const published = DIY_ARTICLES.filter((a) => a.publishDate <= referenceIsoDate).sort((a, b) =>
    b.publishDate.localeCompare(a.publishDate)
  );
  const upcoming = DIY_ARTICLES.filter((a) => a.publishDate > referenceIsoDate).sort((a, b) =>
    a.publishDate.localeCompare(b.publishDate)
  );
  return { published, upcoming };
}

